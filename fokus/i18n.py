STRINGS = {'ru': RU, 'de': DE}


def get_strings(lang):
    """Словарь строк для языка; неизвестный язык → ru."""
    if lang not in STRINGS:
        lang = 'ru'
    return STRINGS[lang]


def missing_keys():
    """Ключи, которых нет в одном из языков (для теста полноты)."""
    ru, de = set(RU), set(DE)
    return {'ru': sorted(de - ru), 'de': sorted(ru - de)}


